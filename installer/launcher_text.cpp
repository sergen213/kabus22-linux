std::string fmt(const char* english, std::initializer_list<std::string> args) {
    const std::string_view text = tx(english); std::string out; out.reserve(text.size() + 64);
    for (std::size_t i = 0; i < text.size(); ++i) {
        if (text[i] == '{' && i + 2 < text.size() && text[i+1] >= '0' && text[i+1] <= '9' && text[i+2] == '}') {
            const auto n = static_cast<std::size_t>(text[i+1] - '0');
            if (n < args.size()) { out += args.begin()[n]; i += 2; continue; }
        }
        out += text[i];
    }
    return out;
}
std::string uiLanguage(const std::string& preference) {
    if (preference == "en" || preference == "tr") return preference;
    if (const char* forced = std::getenv("KABUS22_UI_LANG"); forced && *forced) return std::string_view(forced) == "tr" ? "tr" : "en";
    for (const char* name : {"LC_ALL", "LC_MESSAGES", "LANG"})
        if (const char* locale = std::getenv(name); locale && *locale) return std::string_view(locale).starts_with("tr") ? "tr" : "en";
    return "en";
}
